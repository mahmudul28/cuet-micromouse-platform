class NoisyMicromouse(Micromouse):


    def __init__(
        self,
        maze_size: int,
        start: Tuple[int, int],
        start_heading: str,
        goal_cells: Set[Tuple[int, int]],
        drive_config: Optional[DifferentialDriveConfig] = None,
        sensor_sigma_mm: float = 6.0,
        robot_radius_mm: float = 40.0,
        dt_s: float = 0.01,
        seed: Optional[int] = None,
    ):
        super().__init__(maze_size, start, start_heading, goal_cells)
        rng = random.Random(seed)
        pose = pose_for_cell(start[0], start[1], start_heading, CELL_SIZE_MM)
        drive = DifferentialDrive(drive_config)
        sensors = NoisySensorArray(sigma_mm=sensor_sigma_mm, rng=rng)
        self.physics = RobotPhysics(pose=pose, drive=drive, sensors=sensors,
                                     robot_radius_mm=robot_radius_mm, dt_s=dt_s, rng=rng)
        self.true_maze: Optional[Maze] = None
        self.drift_log: List[Dict] = []
        self.collision_count: int = 0

    def sense_walls(self, true_maze: Maze) -> Dict[str, bool]:
        self.true_maze = true_maze
        reading = self.physics.sensors.read(self.physics.pose, true_maze, CELL_SIZE_MM)
        result = {"front": reading["front_wall"], "left": reading["left_wall"], "right": reading["right_wall"]}
        for rel, direction in self._relative_directions().items():
            if result[rel]:
                self._record_wall(direction)
        return result

    def move_forward(self) -> None:
        r, c = self.position
        if self.known_walls[r, c] & DIR_BIT[self.heading]:
            raise IllegalMoveError(f"Wall ahead at {self.position} facing {self.heading}")
        if self.true_maze is None:

            return super().move_forward()

        result = self.physics.forward_one_cell_physics(self.true_maze, target_heading=self.heading)
        self.drift_log.append(result)
        if result["collided"]:
            self.collision_count += 1

        dr, dc = DELTA[self.heading]
        nr, nc = r + dr, c + dc
        if not (0 <= nr < self.size and 0 <= nc < self.size):
            raise IllegalMoveError("Attempted to move outside the maze boundary")
        self.position = (nr, nc)
        self.visited.add(self.position)
        self.physics.pose = pose_for_cell(nr, nc, self.heading, CELL_SIZE_MM)
        self.history.append({"position": self.position, "heading": self.heading})

    def _physics_turn(self, direction_key: str, grid_turn_fn) -> None:
        result = self.physics.turn_90_physics(direction_key)
        self.drift_log.append(result)
        grid_turn_fn()
        self.physics.pose.theta_rad = math.radians(HEADING_TO_THETA_DEG[self.heading])

    def turn_left(self) -> None:
        self._physics_turn("left", super().turn_left)

    def turn_right(self) -> None:
        self._physics_turn("right", super().turn_right)

    def turn_back(self) -> None:
        self._physics_turn("back", super().turn_back)



