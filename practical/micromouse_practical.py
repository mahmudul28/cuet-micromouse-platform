# 8. CONTINUOUS POSE & DIFFERENTIAL-DRIVE KINEMATICS

HEADING_TO_THETA_DEG: Dict[str, float] = {"E": 0.0, "S": 90.0, "W": 180.0, "N": 270.0}


WALL_FOLLOW_TARGET_MM: float = CELL_SIZE_MM / 2.0


@dataclass
class RobotPose:
    """Continuous robot pose in millimetres / radians (world frame)."""
    x_mm: float
    y_mm: float
    theta_rad: float


def pose_for_cell(row: int, col: int, heading: str, cell_size_mm: float = CELL_SIZE_MM) -> RobotPose:

    return RobotPose(
        x_mm=(col + 0.5) * cell_size_mm,
        y_mm=(row + 0.5) * cell_size_mm,
        theta_rad=math.radians(HEADING_TO_THETA_DEG[heading]),
    )


def _wrap_angle(angle_rad: float) -> float:
    """Wrap an angle (radians) to (-pi, pi]."""
    return (angle_rad + math.pi) % (2 * math.pi) - math.pi


def _clip(value: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, value))


def _trapezoidal_profile(n_steps: int, total: float, dt: float) -> List[float]:

    ramp = max(1, n_steps // 4)
    cruise = max(0, n_steps - 2 * ramp)
    shape = [(i + 1) / ramp for i in range(ramp)] + [1.0] * cruise + [(ramp - i) / ramp for i in range(ramp)]
    shape = (shape + [1.0] * n_steps)[:n_steps]
    shape_sum = sum(shape) if sum(shape) > 0 else 1.0
    scale = total / (dt * shape_sum)
    return [s * scale for s in shape]


def _point_to_line_distance(px: float, py: float, x1: float, y1: float, x2: float, y2: float) -> float:
    """Perpendicular distance from point (px,py) to the line through (x1,y1)-(x2,y2)."""
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy)
    if length < 1e-9:
        return math.hypot(px - x1, py - y1)
    return abs(dy * px - dx * py + x2 * y1 - y2 * x1) / length


@dataclass
class DifferentialDriveConfig:

    wheel_radius_mm: float = 15.0
    wheelbase_mm: float = 80.0
    ticks_per_rev: int = 360
    max_speed_mm_s: float = 500.0
    max_omega_rad_s: float = math.radians(400.0)
    omega_noise_std: float = 0.05


class DifferentialDrive:
    """
        v_left  = v - omega * wheelbase / 2
        v_right = v + omega * wheelbase / 2
        wheel_angular_speed = v_wheel / wheel_radius
    """

    def __init__(self, config: Optional[DifferentialDriveConfig] = None):
        self.config = config or DifferentialDriveConfig()

    @property
    def max_speed_mm_s(self) -> float:
        return self.config.max_speed_mm_s

    @property
    def max_omega_rad_s(self) -> float:
        return self.config.max_omega_rad_s

    @property
    def omega_noise_std(self) -> float:
        return self.config.omega_noise_std

    def wheel_angular_speeds(self, v_mm_s: float, omega_rad_s: float) -> Tuple[float, float]:
        """Inverse kinematics: body (v, omega) -> (left, right) wheel angular speed in rad/s."""
        half_wb = self.config.wheelbase_mm / 2.0
        v_left = v_mm_s - omega_rad_s * half_wb
        v_right = v_mm_s + omega_rad_s * half_wb
        return v_left / self.config.wheel_radius_mm, v_right / self.config.wheel_radius_mm

    def ticks_for(self, wheel_angular_speed_rad_s: float, dt: float) -> float:
        """Simulated encoder tick count accumulated over `dt` at the given
        wheel angular speed (fractional -- callers accumulate and may round
        when reading the 'hardware' counter)."""
        revolutions = wheel_angular_speed_rad_s * dt / (2 * math.pi)
        return revolutions * self.config.ticks_per_rev



# 9. NOISY SENSOR MODEL (RAYCASTING + GAUSSIAN NOISE)
def raycast_distance_mm(
    x_mm: float, y_mm: float, angle_rad: float, maze: Maze,
    cell_size_mm: float = CELL_SIZE_MM, max_range_mm: float = 250.0, step_mm: float = 3.0,
) -> float:
    """
    Approximate ray-marching distance sensor model: steps a ray outward from
    (x_mm, y_mm) at `angle_rad` in small increments, and returns the distance
    at which it first crosses a maze wall (or `max_range_mm` if none found).

    """
    dx, dy = math.cos(angle_rad), math.sin(angle_rad)
    prev_row, prev_col = int(y_mm // cell_size_mm), int(x_mm // cell_size_mm)
    steps = int(max_range_mm / step_mm)
    for i in range(1, steps + 1):
        d = i * step_mm
        x, y = x_mm + dx * d, y_mm + dy * d
        row, col = int(y // cell_size_mm), int(x // cell_size_mm)
        if not (0 <= row < maze.size and 0 <= col < maze.size):
            return d
        if row != prev_row or col != prev_col:
            if col > prev_col and maze.has_wall(prev_row, prev_col, "E"):
                return d
            if col < prev_col and maze.has_wall(prev_row, prev_col, "W"):
                return d
            if row > prev_row and maze.has_wall(prev_row, prev_col, "S"):
                return d
            if row < prev_row and maze.has_wall(prev_row, prev_col, "N"):
                return d
            prev_row, prev_col = row, col
    return max_range_mm


@dataclass
class NoisySensorArray:
    """Simulates the three physical IR wall sensors (front/left/right) with
    additive Gaussian noise on the raw distance reading, then thresholds
    each into a boolean wall/no-wall decision -- exactly mirroring how a
    real sensor's analog reading is thresholded in firmware."""
    sigma_mm: float = 6.0
    wall_threshold_mm: float = 110.0
    max_range_mm: float = 250.0
    rng: random.Random = field(default_factory=random.Random)

    def _noisy(self, true_mm: float) -> float:
        reading = true_mm + self.rng.gauss(0.0, self.sigma_mm)
        return _clip(reading, 0.0, self.max_range_mm)

    def read(self, pose: RobotPose, maze: Maze, cell_size_mm: float = CELL_SIZE_MM) -> Dict:
        theta = pose.theta_rad
        front_true = raycast_distance_mm(pose.x_mm, pose.y_mm, theta, maze, cell_size_mm, self.max_range_mm)
        left_true = raycast_distance_mm(pose.x_mm, pose.y_mm, theta - math.pi / 2, maze, cell_size_mm, self.max_range_mm)
        right_true = raycast_distance_mm(pose.x_mm, pose.y_mm, theta + math.pi / 2, maze, cell_size_mm, self.max_range_mm)

        f, l, r = self._noisy(front_true), self._noisy(left_true), self._noisy(right_true)
        return {
            "front_dist": f, "left_dist": l, "right_dist": r,
            "front_wall": f < self.wall_threshold_mm,
            "left_wall": l < self.wall_threshold_mm,
            "right_wall": r < self.wall_threshold_mm,
        }


def _lateral_wall_error(reading: Dict) -> float:
    """Wall-following error signal for the PID controller: positive means
    the robot is closer to the left wall than the right (should steer
    right), using whichever side sensor(s) currently see a wall."""
    if reading["left_wall"] and reading["right_wall"]:
        return reading["right_dist"] - reading["left_dist"]
    if reading["left_wall"]:
        return WALL_FOLLOW_TARGET_MM - reading["left_dist"]
    if reading["right_wall"]:
        return -(WALL_FOLLOW_TARGET_MM - reading["right_dist"])
    return 0.0



# 10. PID CONTROLLER

class PIDController:


    def __init__(self, kp: float, ki: float, kd: float, output_limit: Optional[float] = None):
        self.kp, self.ki, self.kd = kp, ki, kd
        self.output_limit = output_limit
        self.reset()

    def reset(self) -> None:
        self._integral = 0.0
        self._prev_error: Optional[float] = None

    def update(self, error: float, dt: float) -> float:
        self._integral += error * dt
        derivative = 0.0 if self._prev_error is None else (error - self._prev_error) / dt
        self._prev_error = error
        output = self.kp * error + self.ki * self._integral + self.kd * derivative
        if self.output_limit is not None:
            output = _clip(output, -self.output_limit, self.output_limit)
        return output


# 11. ROBOT PHYSICS ENGINE

class RobotPhysics:


    def __init__(
        self,
        pose: RobotPose,
        drive: Optional[DifferentialDrive] = None,
        sensors: Optional[NoisySensorArray] = None,
        robot_radius_mm: float = 40.0,
        dt_s: float = 0.01,
        rng: Optional[random.Random] = None,
    ):
        self.pose = pose
        self.drive = drive or DifferentialDrive()
        self.rng = rng or random.Random()
        self.sensors = sensors or NoisySensorArray(rng=self.rng)
        self.robot_radius_mm = robot_radius_mm
        self.dt = dt_s

        self.total_left_ticks: float = 0.0
        self.total_right_ticks: float = 0.0
        self.collisions: int = 0


    def _check_collision(self, maze: Maze, cell_size_mm: float) -> bool:
        """True if the robot's circular footprint has crossed into a wall."""
        col = int(self.pose.x_mm // cell_size_mm)
        row = int(self.pose.y_mm // cell_size_mm)
        if not (0 <= row < maze.size and 0 <= col < maze.size):
            return True
        fx = self.pose.x_mm - col * cell_size_mm
        fy = self.pose.y_mm - row * cell_size_mm
        r = self.robot_radius_mm
        if fx < r and maze.has_wall(row, col, "W"):
            return True
        if cell_size_mm - fx < r and maze.has_wall(row, col, "E"):
            return True
        if fy < r and maze.has_wall(row, col, "N"):
            return True
        if cell_size_mm - fy < r and maze.has_wall(row, col, "S"):
            return True
        return False

    def forward_one_cell_physics(
        self, maze: Maze, target_heading: str, cell_size_mm: float = CELL_SIZE_MM,
        n_steps: int = 40, pid: Optional[PIDController] = None,
    ) -> Dict:
        """
        Drive forward exactly one cell length using a trapezoidal
        acceleration/cruise/deceleration speed profile, correcting heading
        with a PID wall-follower fed by noisy side-sensor readings.

        """
        theta_target = math.radians(HEADING_TO_THETA_DEG[target_heading])
        pid = pid or PIDController(kp=0.02, ki=0.0008, kd=0.012, output_limit=self.drive.max_omega_rad_s)
        pid.reset()

        start_x, start_y = self.pose.x_mm, self.pose.y_mm
        speed_profile = _trapezoidal_profile(n_steps, cell_size_mm, self.dt)
        collided = False

        for v in speed_profile:
            reading = self.sensors.read(self.pose, maze, cell_size_mm)
            lateral_error = _lateral_wall_error(reading)
            heading_error = _wrap_angle(theta_target - self.pose.theta_rad)

            omega = pid.update(lateral_error, self.dt) * 0.01 + 0.6 * heading_error
            omega += self.rng.gauss(0.0, self.drive.omega_noise_std)
            omega = _clip(omega, -self.drive.max_omega_rad_s, self.drive.max_omega_rad_s)

            self.pose.x_mm += v * math.cos(self.pose.theta_rad) * self.dt
            self.pose.y_mm += v * math.sin(self.pose.theta_rad) * self.dt
            self.pose.theta_rad = _wrap_angle(self.pose.theta_rad + omega * self.dt)

            w_left, w_right = self.drive.wheel_angular_speeds(v, omega)
            self.total_left_ticks += self.drive.ticks_for(w_left, self.dt)
            self.total_right_ticks += self.drive.ticks_for(w_right, self.dt)

            if self._check_collision(maze, cell_size_mm):
                collided = True
                self.collisions += 1
                break

        ideal_x = start_x + math.cos(theta_target) * cell_size_mm
        ideal_y = start_y + math.sin(theta_target) * cell_size_mm
        lateral_drift = _point_to_line_distance(self.pose.x_mm, self.pose.y_mm, start_x, start_y, ideal_x, ideal_y)
        heading_error_deg = math.degrees(_wrap_angle(theta_target - self.pose.theta_rad))

        return {
            "collided": collided,
            "lateral_drift_mm": lateral_drift,
            "heading_error_deg": heading_error_deg,
            "final_pose": (self.pose.x_mm, self.pose.y_mm, math.degrees(self.pose.theta_rad)),
        }

    def turn_90_physics(self, direction: str, n_steps: int = 25) -> Dict:
        """
        Rotate in place using a trapezoidal angular-velocity profile
        (+/-90 degrees for 'left'/'right', 180 degrees for 'back'), then
        apply a single closed-loop correction pass (as a gyro-equipped
        real robot would) before reporting the residual heading error.
        """
        turn_angle_deg = {"left": -90.0, "right": 90.0, "back": 180.0}[direction]
        theta_start = self.pose.theta_rad
        theta_target = _wrap_angle(theta_start + math.radians(turn_angle_deg))
        sign = 1.0 if turn_angle_deg > 0 else -1.0

        omega_profile = _trapezoidal_profile(n_steps, math.radians(abs(turn_angle_deg)), self.dt)
        for omega_mag in omega_profile:
            omega = sign * omega_mag + self.rng.gauss(0.0, self.drive.omega_noise_std)
            self.pose.theta_rad = _wrap_angle(self.pose.theta_rad + omega * self.dt)
            w_left, w_right = self.drive.wheel_angular_speeds(0.0, omega)
            self.total_left_ticks += self.drive.ticks_for(w_left, self.dt)
            self.total_right_ticks += self.drive.ticks_for(w_right, self.dt)


        residual = _wrap_angle(theta_target - self.pose.theta_rad)
        self.pose.theta_rad = _wrap_angle(
            self.pose.theta_rad + 0.8 * residual + self.rng.gauss(0.0, self.drive.omega_noise_std * self.dt)
        )

        heading_error_deg = math.degrees(_wrap_angle(theta_target - self.pose.theta_rad))
        return {
            "heading_error_deg": heading_error_deg,
            "final_theta_deg": math.degrees(self.pose.theta_rad),
        }



