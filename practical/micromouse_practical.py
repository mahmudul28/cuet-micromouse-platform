def test_noisy_maze_solving(
    num_mazes: int = 20, size: int = 16, seed: Optional[int] = None,
    max_steps: int = 5000, verbose: bool = True, **physics_kwargs,
) -> Dict:
    """
    Runs the *unmodified* Flood Fill exploration + speed-run pipeline on
    `num_mazes` unseen random mazes with the Version 2 physics + noisy
    sensors enabled, to validate the algorithm still reliably solves the
    maze when motion and sensing are no longer perfect.
    """
    rng = random.Random(seed)
    successes = 0
    collisions_total = 0
    drift_samples: List[float] = []
    heading_samples: List[float] = []

    for i in range(num_mazes):
        maze_seed = rng.randint(0, 10**9)
        sim = Simulator(
            random_maze=True, size=size, seed=maze_seed,
            physics=True, physics_seed=rng.randint(0, 10**9), **physics_kwargs,
        )
        ok = sim.run_exploration(max_steps=max_steps, verbose=False)
        if ok:
            sim.run_speed_run(verbose=False)
            successes += 1

        collisions_total += sim.mouse.collision_count
        for rec in sim.mouse.drift_log:
            if "lateral_drift_mm" in rec:
                drift_samples.append(abs(rec["lateral_drift_mm"]))
            if "heading_error_deg" in rec:
                heading_samples.append(abs(rec["heading_error_deg"]))

        if verbose and (i + 1) % 5 == 0:
            print(f"  [{i + 1}/{num_mazes}] cumulative successes: {successes}")

    summary = {
        "num_mazes": num_mazes,
        "success_rate": successes / num_mazes if num_mazes else 0.0,
        "total_collisions": collisions_total,
        "avg_drift_mm": float(np.mean(drift_samples)) if drift_samples else None,
        "avg_heading_error_deg": float(np.mean(heading_samples)) if heading_samples else None,
    }
    if verbose:
        print("\n===== test_noisy_maze_solving (Version 2 validation) =====")
        for k, v in summary.items():
            print(f"{k}: {v}")
        print("============================================================\n")
    return summary



